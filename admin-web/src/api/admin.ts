import { defaultApiClient, type ApiClient } from './http';
import type {
  AdjustLeaveAccountRequest,
  AdminAgentTaskAuditResponse,
  AdminAgentTaskFailureSummaryResponse,
  AdminAgentTaskMetricsResponse,
  AdminAgentTaskResponse,
  AdminAgentTaskTimeoutRunResponse,
  AdminAgentTaskToolCallResponse,
  AgentAclResponse,
  AgentResponse,
  AgentTaskListQuery,
  AgentTaskTimeoutScanResponse,
  AgentTaskTimeoutRunQuery,
  AgentToolResponse,
  AgentVersionResponse,
  CleanupJobRunResponse,
  AttachmentRefResponse,
  ConfirmUploadRequest,
  CreateAgentRequest,
  CreateAgentVersionRequest,
  CreateDownloadTicketRequest,
  CreateLeaveTypeRequest,
  CreateRagflowSpaceRequest,
  CreateLlmModelRequest,
  CreateUploadTicketRequest,
  CurrentUserResponse,
  DownloadTicketResponse,
  EntityId,
  GrantAgentAclRequest,
  LeaveAccountResponse,
  LeaveTypeResponse,
  LlmModelResponse,
  LoginRequest,
  LoginResponse,
  OrgDepartmentSaveRequest,
  OrgDepartmentTreeNodeResponse,
  OrgPositionResponse,
  OrgPositionSaveRequest,
  OrgUserCreateRequest,
  OrgUserDetailResponse,
  OrgUserListQuery,
  OrgUserSummaryResponse,
  PageResult,
  RunCleanupJobRequest,
  SaveRagflowAclRequest,
  StorageSummaryResponse,
  UpdateAgentVersionRequest,
  WorkflowRequestDetailResponse,
  WorkflowRequestListQuery,
  WorkflowRequestSummaryResponse,
  WorkflowTaskActionResponse,
  WorkflowTemplateResponse,
  WorkflowTemplateVersionResponse,
  WorkflowValidateRequest,
  WorkflowValidationResponse,
  RagflowAclResponse,
  RagflowDocumentResponse,
  RagflowGlobalSettingResponse,
  RagflowSearchTestResponse,
  RagflowSpaceResponse,
  UploadTicketResponse,
  UpdateRagflowGlobalSettingRequest,
  UpdateRagflowSpaceRequest,
} from './types';

const pathId = (value: EntityId) => encodeURIComponent(String(value));

export function createAdminApi(client: ApiClient = defaultApiClient) {
  return {
    auth: {
      login: (request: LoginRequest) => client.post<LoginResponse>('/api/admin/auth/login', request),
      logout: () => client.post<void>('/api/admin/auth/logout'),
      me: () => client.get<CurrentUserResponse>('/api/admin/auth/me'),
    },
    agentTasks: {
      metrics: () => client.get<AdminAgentTaskMetricsResponse>('/api/admin/agent-tasks/metrics'),
      failureSummary: () => client.get<AdminAgentTaskFailureSummaryResponse[]>('/api/admin/agent-tasks/failure-summary'),
      list: (query: AgentTaskListQuery = {}) => client.get<PageResult<AdminAgentTaskResponse>>('/api/admin/agent-tasks', { query }),
      detail: (taskId: EntityId) => client.get<AdminAgentTaskResponse>(`/api/admin/agent-tasks/${pathId(taskId)}`),
      toolCalls: (taskId: EntityId) => client.get<AdminAgentTaskToolCallResponse[]>(`/api/admin/agent-tasks/${pathId(taskId)}/tool-calls`),
      audits: (taskId: EntityId) => client.get<AdminAgentTaskAuditResponse[]>(`/api/admin/agent-tasks/${pathId(taskId)}/audits`),
      timeoutScan: (batchSize: number) => client.post<AgentTaskTimeoutScanResponse>('/api/admin/agent-tasks/timeout-scan', { batchSize }),
      timeoutRuns: (query: AgentTaskTimeoutRunQuery = {}) => client.get<PageResult<AdminAgentTaskTimeoutRunResponse>>('/api/admin/agent-tasks/timeout-scan-runs', { query }),
    },
    workflow: {
      requests: (query: WorkflowRequestListQuery = {}) => client.get<PageResult<WorkflowRequestSummaryResponse>>('/api/admin/workflow/requests', { query }),
      requestDetail: (requestId: EntityId) => client.get<WorkflowRequestDetailResponse>(`/api/admin/workflow/requests/${pathId(requestId)}`),
      requestActions: (requestId: EntityId) => client.get<WorkflowTaskActionResponse[]>(`/api/admin/workflow/requests/${pathId(requestId)}/actions`),
      templates: (processCode?: string) => client.get<WorkflowTemplateResponse[]>('/api/admin/workflow/templates', { query: { processCode } }),
      templateVersions: (templateId: EntityId) => client.get<WorkflowTemplateVersionResponse[]>(`/api/admin/workflow/templates/${pathId(templateId)}/versions`),
    },
    leave: {
      types: () => client.get<LeaveTypeResponse[]>('/api/admin/leave/types'),
      createType: (request: CreateLeaveTypeRequest) => client.post<LeaveTypeResponse>('/api/admin/leave/types', request),
      accounts: (query: { userId?: EntityId; leaveTypeId?: EntityId } = {}) => client.get<LeaveAccountResponse[]>('/api/admin/leave/accounts', { query }),
      adjustAccount: (request: AdjustLeaveAccountRequest) => client.post<LeaveAccountResponse>('/api/admin/leave/accounts/adjustments', request),
    },
    org: {
      departmentTree: () => client.get<OrgDepartmentTreeNodeResponse[]>('/api/admin/departments/tree'),
      createDepartment: (request: OrgDepartmentSaveRequest) => client.post<EntityId>('/api/admin/departments', request),
      updateDepartment: (deptId: EntityId, request: OrgDepartmentSaveRequest) => client.put<void>(`/api/admin/departments/${pathId(deptId)}`, request),
      positions: () => client.get<OrgPositionResponse[]>('/api/admin/positions'),
      createPosition: (request: OrgPositionSaveRequest) => client.post<EntityId>('/api/admin/positions', request),
      updatePosition: (positionId: EntityId, request: OrgPositionSaveRequest) => client.put<void>(`/api/admin/positions/${pathId(positionId)}`, request),
      users: (query: OrgUserListQuery = {}) => client.get<PageResult<OrgUserSummaryResponse>>('/api/admin/users', { query }),
      userDetail: (userId: EntityId) => client.get<OrgUserDetailResponse>(`/api/admin/users/${pathId(userId)}`),
      createUser: (request: OrgUserCreateRequest) => client.post<EntityId>('/api/admin/users', request),
    },
    agentConfig: {
      list: (pageNo = 1, pageSize = 20, keyword?: string) => client.get<PageResult<AgentResponse>>('/api/admin/agents', { query: { pageNo, pageSize, keyword } }),
      detail: (agentId: EntityId) => client.get<AgentResponse>(`/api/admin/agents/${pathId(agentId)}`),
      create: (request: CreateAgentRequest) => client.post<AgentResponse>('/api/admin/agents', request),
      versions: (agentId: EntityId) => client.get<AgentVersionResponse[]>(`/api/admin/agents/${pathId(agentId)}/versions`),
      createVersion: (agentId: EntityId, request: CreateAgentVersionRequest) => client.post<AgentVersionResponse>(`/api/admin/agents/${pathId(agentId)}/versions`, request),
      updateVersion: (versionId: EntityId, request: UpdateAgentVersionRequest) => client.put<AgentVersionResponse>(`/api/admin/agents/versions/${pathId(versionId)}`, request),
      acl: (agentId: EntityId) => client.get<AgentAclResponse[]>(`/api/admin/agents/${pathId(agentId)}/acl`),
      grantAcl: (agentId: EntityId, request: GrantAgentAclRequest) => client.post<AgentAclResponse>(`/api/admin/agents/${pathId(agentId)}/acl`, request),
      validateWorkflow: (request: WorkflowValidateRequest) => client.post<WorkflowValidationResponse>('/api/admin/agents/workflows/validate', request),
      publishVersion: (versionId: EntityId) => client.post<AgentResponse>(`/api/admin/agents/versions/${pathId(versionId)}/publish`),
      disable: (agentId: EntityId) => client.post<AgentResponse>(`/api/admin/agents/${pathId(agentId)}/disable`),
      enable: (agentId: EntityId) => client.post<AgentResponse>(`/api/admin/agents/${pathId(agentId)}/enable`),
      tools: () => client.get<AgentToolResponse[]>('/api/admin/agents/tools'),
      trialRun: (request: { nodeId: string; inputJson?: string; workflowConfigJson?: string; systemPrompt?: string; modelConfigJson?: string }) => client.post<{ success: boolean; outputJson?: string; errorMessage?: string; durationMs: number }>('/api/admin/agents/trial-run', request),
      workflowRun: (request: { inputJson: string; versionId?: EntityId; workflowConfigJson?: string; systemPrompt?: string; modelConfigJson?: string }) => client.post<{ success: boolean; finalReply?: string; steps?: { nodeId: string; type: string; status: string; output?: string; nextNodeId?: string; durationMs: number }[]; errorMessage?: string; durationMs: number }>('/api/admin/agents/workflow-run', request),
    },
    files: {
      storageSummary: () => client.get<StorageSummaryResponse>('/api/admin/files/storage-summary'),
      runCleanupJob: (request: RunCleanupJobRequest) => client.post<CleanupJobRunResponse>('/api/admin/files/cleanup-jobs/run', request),
      createUploadTicket: (request: CreateUploadTicketRequest) => client.post<UploadTicketResponse>('/api/admin/files/upload-tickets', request),
      confirmUpload: (request: ConfirmUploadRequest) => client.post<AttachmentRefResponse>('/api/admin/files/confirm-upload', request),
      createDownloadTicket: (attachmentRefId: EntityId, request: CreateDownloadTicketRequest) => client.post<DownloadTicketResponse>(`/api/admin/files/${pathId(attachmentRefId)}/download-tickets`, request),
      downloadUrl: (ticketNo: string) => `/api/admin/files/download/${encodeURIComponent(ticketNo)}`,
    },
    ragflow: {
      settings: () => client.get<RagflowGlobalSettingResponse>('/api/admin/ragflow/settings'),
      updateSettings: (request: UpdateRagflowGlobalSettingRequest) => client.put<RagflowGlobalSettingResponse>('/api/admin/ragflow/settings', request),
      spaces: (pageNo = 1, pageSize = 20, keyword?: string) => client.get<PageResult<RagflowSpaceResponse>>('/api/admin/ragflow/spaces', { query: { pageNo, pageSize, keyword } }),
      createSpace: (request: CreateRagflowSpaceRequest) => client.post<RagflowSpaceResponse>('/api/admin/ragflow/spaces', request),
      updateSpace: (spaceId: EntityId, request: UpdateRagflowSpaceRequest) => client.put<RagflowSpaceResponse>(`/api/admin/ragflow/spaces/${pathId(spaceId)}`, request),
      acl: (spaceId: EntityId) => client.get<RagflowAclResponse[]>(`/api/admin/ragflow/spaces/${pathId(spaceId)}/acl`),
      saveAcl: (spaceId: EntityId, request: SaveRagflowAclRequest) => client.put<RagflowAclResponse[]>(`/api/admin/ragflow/spaces/${pathId(spaceId)}/acl`, request),
      documents: (spaceId: EntityId) => client.get<RagflowDocumentResponse[]>(`/api/admin/ragflow/spaces/${pathId(spaceId)}/documents`),
      addDocument: (spaceId: EntityId, attachmentRefId: EntityId) => client.post<RagflowDocumentResponse>(`/api/admin/ragflow/spaces/${pathId(spaceId)}/documents`, { attachmentRefId }),
      reingestDocument: (spaceId: EntityId, documentId: EntityId) => client.post<RagflowDocumentResponse>(`/api/admin/ragflow/spaces/${pathId(spaceId)}/documents/${pathId(documentId)}/reingest`),
      deleteDocument: (spaceId: EntityId, documentId: EntityId) => client.delete<void>(`/api/admin/ragflow/spaces/${pathId(spaceId)}/documents/${pathId(documentId)}`),
      searchTest: (spaceId: EntityId, query: string) => client.post<RagflowSearchTestResponse>(`/api/admin/ragflow/spaces/${pathId(spaceId)}/search-test`, { query }),
    },
    llmModels: {
      list: () => client.get<LlmModelResponse[]>('/api/admin/agents/llm-models'),
      create: (request: CreateLlmModelRequest) => client.post<LlmModelResponse>('/api/admin/agents/llm-models', request),
      update: (modelId: EntityId, request: CreateLlmModelRequest) => client.put<LlmModelResponse>(`/api/admin/agents/llm-models/${pathId(modelId)}`, request),
      remove: (modelId: EntityId) => client.delete(`/api/admin/agents/llm-models/${pathId(modelId)}`),
      test: (modelId: EntityId) => client.post<{ success: boolean; message: string; sampleReply?: string; durationMs: number }>(`/api/admin/agents/llm-models/${pathId(modelId)}/test`),
    },
  };
}

export const adminApi = createAdminApi();
